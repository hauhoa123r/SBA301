"""Generate the SQL guard and classpath copy of the reviewed Hibernate contract.

Run from any directory. Use --check in CI to reject a stale generated SQL file.
"""
from pathlib import Path
import csv
import re
import sys

ROOT = Path(__file__).resolve().parent
TEST_CONTRACT = ROOT.parent / "backend/src/test/resources/schema/jpa-schema-contract.tsv"


def literal(value):
    return "'" + value.replace("'", "''") + "'"


def generate():
    rows = []
    for name in ("jpa-schema-contract.tsv", "native-schema-contract.tsv"):
        rows.extend(csv.reader((ROOT / name).read_text(encoding="utf-8").splitlines(), delimiter="\t"))
    columns, keys = [], []
    families = {
        "bigint": "bigint", "integer": "int", "int": "int", "smallint": "smallint", "tinyint": "tinyint",
        "bit": "bit,tinyint", "boolean": "bit,tinyint", "date": "date",
        "datetime": "datetime,timestamp", "timestamp": "datetime,timestamp",
        "json": "json", "decimal": "decimal", "float": "float", "double": "double",
        "varchar": "varchar,char,text,mediumtext,longtext", "char": "varchar,char",
        "enum": "enum,varchar,char", "text": "text,mediumtext,longtext",
        "mediumtext": "mediumtext,longtext", "longtext": "longtext",
    }
    for row in rows:
        if row[0] == "COLUMN":
            _, table, column, data_type, nullable = row
            family = re.match(r"\w+", data_type.lower()).group(0)
            length = int(data_type.split("(")[1].split(")")[0]) if family in ("varchar", "char") else 0
            precision, scale = map(int, data_type.split("(")[1].split(")")[0].split(",")) if family == "decimal" else (0, 0)
            values = [table, column, families[family], 1 if nullable == "false" else 0, length, precision, scale]
            columns.append("SELECT " + ", ".join(literal(v) if isinstance(v, str) else str(v) for v in values))
        else:
            kind, table, names, *reference = row
            names = ",".join(sorted(names.split(",")))
            ref_table = reference[0] if reference else ""
            ref_names = ",".join(sorted(reference[1].split(","))) if reference else ""
            keys.append("SELECT " + ", ".join(map(literal, [kind.replace("_", " "), table, names, ref_table, ref_names])))
    return """-- Generated by generate-schema-check.py; read-only, empty output means compatible.
-- Covers all JPA columns, primary/unique keys and relationships, including join tables.
WITH expected_columns(table_name, column_name, allowed_types, required, min_length, num_precision, num_scale) AS (
""" + "\nUNION ALL\n".join(columns) + """
), expected_keys(kind, table_name, columns_list, ref_table, ref_columns) AS (
""" + "\nUNION ALL\n".join(keys) + """
), actual_keys AS (
    SELECT tc.CONSTRAINT_TYPE AS kind, tc.TABLE_NAME AS table_name,
           GROUP_CONCAT(k.COLUMN_NAME ORDER BY k.COLUMN_NAME) AS columns_list,
           COALESCE(MAX(k.REFERENCED_TABLE_NAME), '') AS ref_table,
           COALESCE(GROUP_CONCAT(k.REFERENCED_COLUMN_NAME ORDER BY k.REFERENCED_COLUMN_NAME), '') AS ref_columns
    FROM information_schema.TABLE_CONSTRAINTS tc
    JOIN information_schema.KEY_COLUMN_USAGE k
      ON k.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA AND k.TABLE_NAME=tc.TABLE_NAME
     AND k.CONSTRAINT_NAME=tc.CONSTRAINT_NAME
    WHERE tc.CONSTRAINT_SCHEMA=DATABASE()
    GROUP BY tc.CONSTRAINT_TYPE, tc.TABLE_NAME, tc.CONSTRAINT_NAME
)
SELECT CONCAT('column mismatch: ', e.table_name, '.', e.column_name) AS violation
FROM expected_columns e
LEFT JOIN information_schema.COLUMNS c
  ON c.TABLE_SCHEMA=DATABASE() AND c.TABLE_NAME=e.table_name AND c.COLUMN_NAME=e.column_name
WHERE c.COLUMN_NAME IS NULL
   OR (e.required=1 AND c.IS_NULLABLE<>'NO')
   OR FIND_IN_SET(c.DATA_TYPE, e.allowed_types)=0
   OR (e.min_length>0 AND COALESCE(c.CHARACTER_MAXIMUM_LENGTH,0)<e.min_length)
   OR (e.num_precision>0 AND (c.NUMERIC_PRECISION<>e.num_precision OR c.NUMERIC_SCALE<>e.num_scale))
UNION ALL
SELECT CONCAT('constraint mismatch: ', e.kind, ' ', e.table_name, '(', e.columns_list, ')')
FROM expected_keys e
WHERE NOT EXISTS (
    SELECT 1 FROM actual_keys a WHERE a.table_name=e.table_name AND a.columns_list=e.columns_list
      AND (a.kind=e.kind OR (e.kind='UNIQUE' AND a.kind='PRIMARY KEY'))
      AND a.ref_table=e.ref_table AND a.ref_columns=e.ref_columns
)
UNION ALL
SELECT 'lesson_progress.position_seconds must be INT NOT NULL DEFAULT 0'
WHERE NOT EXISTS (
    SELECT 1 FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
      AND TABLE_NAME='lesson_progress' AND COLUMN_NAME='position_seconds'
      AND DATA_TYPE='int' AND IS_NULLABLE='NO' AND COLUMN_DEFAULT='0'
);
"""


if __name__ == "__main__":
    output = ROOT / "check-schema.sql"
    content = generate()
    if "--check" in sys.argv:
        if not output.is_file() or output.read_text(encoding="utf-8") != content:
            raise SystemExit("check-schema.sql is stale; regenerate after reviewing the JPA contract")
        if not TEST_CONTRACT.is_file() or TEST_CONTRACT.read_bytes() != (ROOT / "jpa-schema-contract.tsv").read_bytes():
            raise SystemExit("Classpath JPA contract is missing or stale; run database/generate-schema-check.py to sync it")
    else:
        if not output.is_file() or output.read_text(encoding="utf-8") != content:
            output.write_text(content, encoding="utf-8", newline="\n")
        TEST_CONTRACT.parent.mkdir(parents=True, exist_ok=True)
        TEST_CONTRACT.write_bytes((ROOT / "jpa-schema-contract.tsv").read_bytes())
